"""CLI: ``causal4j-pipeline run|discover|fit|emit|validate``.

Everything is driven by the YAML config; subcommands other than ``run`` are
conveniences that override or shortcut parts of it. ``--dry-run`` prints the
DSL to stdout instead of writing files.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from causal4j_pipeline import registry
from causal4j_pipeline.config import load_config, parse_config
from causal4j_pipeline.emit.dsl import emit_dsl
from causal4j_pipeline.io.readers import read_dag
from causal4j_pipeline.pipeline import Pipeline, run as run_pipeline


def _cmd_run(args: argparse.Namespace) -> int:
    result = run_pipeline(args.config, dry_run=args.dry_run)
    if args.dry_run or not result.dsl_path:
        print(result.dsl_text)
    else:
        print(f"wrote {result.dsl_path}")
        if result.provenance_path:
            print(f"wrote {result.provenance_path}")
    _print_report_summary(result.report)
    return 0


def _cmd_discover(args: argparse.Namespace) -> int:
    cfg = load_config(args.config)
    if not cfg.has_discovery:
        print("config has no 'discovery' section", file=sys.stderr)
        return 2
    p = Pipeline.from_config(cfg)
    # Discovery-only: skip fit/refute, print or write the structural model.
    p._hypothesis = None
    p._refute_tests = []
    result = p.run_config(cfg, dry_run=args.dry_run)
    print(result.dsl_text if args.dry_run or not result.dsl_path else f"wrote {result.dsl_path}")
    _print_report_summary(result.report)
    return 0


def _cmd_fit(args: argparse.Namespace) -> int:
    cfg = load_config(args.config)
    if not cfg.has_dag_input:
        print("config has no 'dag' section — 'fit' is Mode B (DAG + data)", file=sys.stderr)
        return 2
    result = Pipeline.from_config(cfg).run_config(cfg, dry_run=args.dry_run)
    print(result.dsl_text if args.dry_run or not result.dsl_path else f"wrote {result.dsl_path}")
    _print_report_summary(result.report)
    return 0


def _cmd_emit(args: argparse.Namespace) -> int:
    """Re-serialize a DAG file to .causal without data (structure only)."""
    model = read_dag(args.dag, args.format)
    if args.model_name:
        model.name = args.model_name
    text = emit_dsl(model, header="Generated by causal4j-pipeline emit")
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(text)
        print(f"wrote {args.out}")
    else:
        print(text)
    return 0


def _cmd_validate(args: argparse.Namespace) -> int:
    """Structural round-trip check of a .causal file (acyclicity, edges, decls).

    Note: the authoritative parser is the Java DSL module's ANTLR grammar; this
    validates the model subset the pipeline emits.
    """
    try:
        model = read_dag(args.file, "causal")
        model.validate()
    except Exception as e:
        print(f"INVALID: {e}", file=sys.stderr)
        return 1
    print(f"OK: model '{model.name}' — {len(model.variables)} variables, {len(model.edges)} edges, acyclic")
    return 0


def _cmd_registry(args: argparse.Namespace) -> int:
    registry.load_plugins()
    # Import stage modules so their registrations run.
    import causal4j_pipeline.stages.discover  # noqa: F401
    import causal4j_pipeline.stages.fit  # noqa: F401
    import causal4j_pipeline.stages.refute  # noqa: F401
    import causal4j_pipeline.stages.resolve  # noqa: F401
    import causal4j_pipeline.io.readers  # noqa: F401

    print(json.dumps({
        "discovery": list(registry.DISCOVERY.names()),
        "hypotheses": list(registry.HYPOTHESES.names()),
        "resolvers": list(registry.RESOLVERS.names()),
        "refuters": list(registry.REFUTERS.names()),
        "readers": list(registry.READERS.names()),
    }, indent=2))
    return 0


def _print_report_summary(report: dict) -> None:
    disc = report.get("discovery")
    if disc:
        print(f"# discovery: {disc.get('algorithm')} -> {disc.get('n_directed')} directed, "
              f"{disc.get('n_undirected')} unoriented", file=sys.stderr)
    res = report.get("resolution", {})
    if res.get("guesses"):
        print(f"# resolution: {len(res['guesses'])} heuristic orientation(s) — check the provenance file",
              file=sys.stderr)
    ref = report.get("refutation")
    if ref:
        status = "passed" if ref.get("passed") else "FAILED"
        print(f"# refutation: {status} ({', '.join(ref.get('tests', {}))})", file=sys.stderr)


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(prog="causal4j-pipeline",
                                 description="Causal4j ingestion pipeline: discovery + SEM fitting -> .causal DSL")
    sub = ap.add_subparsers(dest="command", required=True)

    p_run = sub.add_parser("run", help="full chain from a YAML config")
    p_run.add_argument("config")
    p_run.add_argument("--dry-run", action="store_true", help="print DSL to stdout, write nothing")
    p_run.set_defaults(func=_cmd_run)

    p_disc = sub.add_parser("discover", help="Mode A, structure only (no fit/refute)")
    p_disc.add_argument("config")
    p_disc.add_argument("--dry-run", action="store_true")
    p_disc.set_defaults(func=_cmd_discover)

    p_fit = sub.add_parser("fit", help="Mode B: DAG + data + hypothesis")
    p_fit.add_argument("config")
    p_fit.add_argument("--dry-run", action="store_true")
    p_fit.set_defaults(func=_cmd_fit)

    p_emit = sub.add_parser("emit", help="convert a DAG file to .causal (no data)")
    p_emit.add_argument("dag", help="DAG file (gml, dot, edge-list csv, causal)")
    p_emit.add_argument("--format", help="override format inference")
    p_emit.add_argument("--model-name")
    p_emit.add_argument("--out", help="output path (stdout when omitted)")
    p_emit.set_defaults(func=_cmd_emit)

    p_val = sub.add_parser("validate", help="round-trip check a .causal file")
    p_val.add_argument("file")
    p_val.set_defaults(func=_cmd_validate)

    p_reg = sub.add_parser("registry", help="list registered algorithms/hypotheses/policies")
    p_reg.set_defaults(func=_cmd_registry)

    return ap


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return args.func(args)
    except Exception as e:
        print(f"error: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
