"""Table III: per-dataset statistics, as CSV and as a LaTeX tabular body."""
import math

import networkx as nx

HEADER = ["dataset", "family", "n", "m", "density", "longest_path", "closure_bytes"]


def row(name: str, family: str, g: nx.DiGraph):
    n, m = g.number_of_nodes(), g.number_of_edges()
    return {
        "dataset": name,
        "family": family,
        "n": n,
        "m": m,
        # fraction of the n(n-1)/2 edges a DAG on n nodes can have
        "density": f"{m / (n * (n - 1) / 2):.6f}" if n > 1 else "0",
        "longest_path": nx.dag_longest_path_length(g),  # in edges
        "closure_bytes": 2 * n * math.ceil(n / 64) * 8,  # ancestor + descendant bitsets
    }


def human_bytes(b: int) -> str:
    """Decimal units as in the paper: 128~B, 2.2~KB, 283~KB, 25~MB."""
    for unit, scale in (("GB", 1e9), ("MB", 1e6), ("KB", 1e3)):
        if b >= scale:
            v = b / scale
            return f"{v:.1f}~{unit}" if v < 10 else f"{v:.0f}~{unit}"
    return f"{b}~B"


def latex(rows) -> str:
    """One line per bnlearn network, covid, and a single summary line for the synthetic grid."""
    lines = ["% Generated by `causal4j-bench stats` from bench/datasets/datasets.csv. Do not edit."]
    for r in rows:
        if r["family"] == "synthetic":
            continue
        name = "COVID-19" if r["dataset"] == "covid" else f"\\textsc{{{r['dataset']}}}"
        lines.append(f"{name} & {r['n']} & {r['m']} & {r['longest_path']} & "
                     f"{human_bytes(int(r['closure_bytes']))} \\\\")
    syn = [r for r in rows if r["family"] == "synthetic"]
    if syn:
        ns = sorted({int(r["n"]) for r in syn})
        ms = [int(r["m"]) for r in syn]
        lp = [int(r["longest_path"]) for r in syn]
        cb = max(int(r["closure_bytes"]) for r in syn)
        lines.append(f"synthetic ({len(syn)} DAGs) & {ns[0]}--{ns[-1]} & {min(ms)}--{max(ms)} & "
                     f"{min(lp)}--{max(lp)} & $\\le$ {human_bytes(cb)} \\\\")
    return "\n".join(lines) + "\n"
